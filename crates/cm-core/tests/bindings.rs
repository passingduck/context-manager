//! Writes `ui/src/gen/api-map.ts` from the operation table. `ts-rs` writes one file per type
//! through its own export tests; this file is the one thing it cannot know: which types an
//! operation takes and returns. `scripts/check.sh` fails when regeneration changes either.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::PathBuf;

use cm_core::api::operations;

fn gen_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../ui/src/gen")
}

#[test]
fn export_api_map() {
    let ops = operations();
    // `Array<AgentInfo>` names its element type but does not report it as a dependency, so the
    // imports are the capitalized words in the type strings. A dependency report supplies the
    // path of a type that lives outside the export root, such as `serde_json/JsonValue`.
    let known: BTreeMap<String, String> = ops.iter().flat_map(|op| op.imports.clone()).collect();
    let imports: BTreeSet<(String, String)> = ops
        .iter()
        .flat_map(|op| {
            format!("{} {}", op.args, op.result)
                .split(|c: char| !c.is_alphanumeric())
                .map(str::to_owned)
                .collect::<Vec<_>>()
        })
        .filter(|word| word.chars().next().is_some_and(char::is_uppercase) && word != "Array")
        .map(|word| {
            let path = known
                .get(&word)
                .cloned()
                .unwrap_or_else(|| format!("{word}.ts"));
            (word, path)
        })
        .collect();

    let mut out = String::from(
        "// Generated by `cargo test -p cm-core --test bindings`. Do not edit by hand.\n",
    );
    for (name, path) in &imports {
        let module = path.strip_suffix(".ts").unwrap_or(path);
        writeln!(out, "import type {{ {name} }} from \"./{module}\";").unwrap();
    }
    out.push_str("\nexport interface ApiMap {\n");
    for op in &ops {
        writeln!(
            out,
            "  {}: {{ args: {}; result: {} }};",
            op.name, op.args, op.result
        )
        .unwrap();
    }
    out.push_str("}\n\nexport type Op = keyof ApiMap;\n");

    let dir = gen_dir();
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("api-map.ts"), out).unwrap();
}
